const encodePersonalLargePath = (path) => encodeURI(path).replace(/#/g, '%23');

const getPersonalLargeMediaItems = (build) => {
  const images = Array.isArray(build.images) ? build.images : [];
  const media = images.map((src, index) => ({
    type: 'image',
    src,
    alt: `${build.title} large personal home image ${index + 1}.`
  }));

  if (build.video) {
    media.push({
      type: 'video',
      src: build.video,
      alt: `${build.title} large personal home video tour.`
    });
  }

  return media;
};

const renderPersonalLargeMedia = (item) => {
  const src = encodePersonalLargePath(item.src);
  if (item.type === 'video') {
    return `<video class="gallery-image" src="${src}" muted playsinline loop preload="metadata" aria-label="${item.alt}"></video>`;
  }
  return `<img class="gallery-image" src="${src}" alt="${item.alt}">`;
};

